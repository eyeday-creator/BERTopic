def _normalize(text):
    return re.sub(r'\s+', '', str(text)).lower()

_NORM_KEYWORDS = [(kw, _normalize(kw)) for kw in CORE_KEYWORDS]

def relevance_score(title, description):
    """제목+설명의 핵심 복합어 포함 정도를 점수화 (제목 매칭 가중치 3, 설명 1)."""
    norm_title = _normalize(title)
    norm_all = _normalize(f"{title} {description}")
    score, matched = 0, []
    for kw_orig, kw_norm in _NORM_KEYWORDS:
        if kw_norm in norm_all:
            score += 3 if kw_norm in norm_title else 1
            matched.append(kw_orig)
    return score, matched

