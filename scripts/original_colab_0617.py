# 2. 다국어 임베딩 모델 로드 (BERTopic 사용 모델과 동일하여 일관성 유지)
print("⏳ 임베딩 모델을 불러오는 중입니다...")
model = SentenceTransformer("paraphrase-multilingual-MiniLM-L12-v2")

# 3. 기준 문장(Anchor Text) 정의
# 이 문장과 의미적으로 가까운 댓글들을 추출하게 됩니다.
anchor_text = "초등학교, 중학교, 고등학교 학교 현장의 인공지능(AI) 교육 도입과 AI 디지털 교과서 활용에 대한 교사, 학생, 학부모의 긍정적인 기대와 부정적인 문제점 우려"

# 4. 벡터 임베딩 변환 (코랩 GPU 활용 시 1~2분 소요)
print("🧠 기준 문장 및 댓글 전체의 문맥 벡터를 계산하고 있습니다...")
anchor_embedding = model.encode([anchor_text])
comment_embeddings = model.encode(df_raw['text_content'].tolist(), show_progress_bar=True)

# 5. 코사인 유사도 계산 (-1 ~ 1 사이의 값)
similarities = cosine_similarity(anchor_embedding, comment_embeddings)[0]
