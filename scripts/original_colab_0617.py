def clean_text_for_embedding(text):
    # 1. URL 제거
    text = re.sub(r'http\S+', '', str(text))

    # 2. Kiwi로 형태소 분석 및 원형 복원
    # tokenize()에 normalize=True를 주면 오탈자 교정 및 원형 복원이 기본적으로 작동합니다.
    tokens = kiwi.tokenize(text, normalize_coda=True)

    cleaned_words = []
    for t in tokens:
        word = t.form  # 형태소 단어 (예: '먹다'의 '먹')
        pos = t.tag    # 품사 태그 (예: 'VV', 'NNG')

        # ① Kiwi 품사 태그 기준 제거 대상 (조사, 어미, 문장부호 등)
        # J로 시작하는 태그: 조사 (JKS, JKB, JX 등)
        # E로 시작하는 태그: 어미 (EC, EF, ETM 등)
        # S로 시작하는 태그: 부호 및 특수문자 (SF, SP, SO 등)
        if pos.startswith('J') or pos.startswith('E') or pos.startswith('S'):
            continue

        # ② 최종 필터링: 불용어 리스트에 없고, 2글자 이상인 것만 저장
        # (용언의 경우 '먹', '가' 처럼 어근만 남으므로 필요에 따라 길이 제한을 조절하세요)
        if word not in stop_words_list and len(word) > 1:
            cleaned_words.append(word)

    # 3. 다시 하나의 문장으로 결합
    return ' '.join(cleaned_words).strip()

