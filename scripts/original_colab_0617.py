# 6. 임계값(Threshold) 기반 필터링
# 유사도 점수가 0.25 이상인 문서만 '관련성 높음'으로 판단
# (일반적으로 0.2 ~ 0.3 사이에서 유의미한 군집이 형성됩니다)
